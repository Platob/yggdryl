  await step('wheel and scrollbar: the view scrolls, tiles arrive, the mirror follows', async () => {
    await settled()
    const p = await cellPoint('C5')
    await page.mouse.move(p.x, p.y)
    await page.mouse.wheel(0, 3000)
    await page.waitForFunction(() => Number((document.getElementById('grid-mirror').dataset.top || 'A0').replace(/^[A-Z]+/, '')) > 100)
    await settled()
    assert.ok(Number((await mirror('data-top')).replace(/^[A-Z]+/, '')) > 100)
    await page.mouse.wheel(600, 0)
    await page.waitForFunction(() => !/^A\d/.test(document.getElementById('grid-mirror').dataset.top))
    await settled()
    await shot('05-scrolled')
    // Drag the vertical thumb to the bottom of its track.
    const thumb = await page.locator('#vscroll .thumb').boundingBox()
    const track = await page.locator('#vscroll').boundingBox()
    await page.mouse.move(thumb.x + thumb.width / 2, thumb.y + thumb.height / 2)
    await page.mouse.down()
    await page.mouse.move(thumb.x + thumb.width / 2, track.y + track.height + 50, { steps: 5 })
    await page.mouse.up()
    await settled()
    const top = Number((await mirror('data-top')).replace(/^[A-Z]+/, ''))
    assert.ok(top > 400, 'thumb at the bottom shows the end of the used range: ' + top)
    await press('Control+Home')
    await settled()
    assert.strictEqual(await mirror('data-top'), 'A2')
  })

