    const tabs = await page.$$eval('#sheet-tabs [role=tab]', (n) => n.map((x) => x.textContent))
    assert.deepStrictEqual(tabs, ['Data', 'Chart1', 'Report', 'Far'])
    await press('Control+PageDown')
    await waitMirror('data-sheet', '2')
    await settled()
    assert.strictEqual(await namebox(), '')
    await page.waitForTimeout(120) // longer than the formula bar's lookup delay: nothing stale may land
    assert.strictEqual(await page.inputValue('#formula'), '')
    assert.strictEqual(await page.isVisible('#vscroll .thumb'), false)
    assert.strictEqual(await mirror('data-rows'), '0')
    assert.strictEqual(await page.getAttribute('#sheet-tab-2', 'aria-selected'), 'true')
    await shot('06-chartsheet')
    await press('Control+PageDown')
    await waitMirror('data-sheet', '3')
    await settled()
    assert.strictEqual(await namebox(), 'B3', 'Report opens below and right of its frozen pane')
    assert.strictEqual(await cellText('D2'), '$1,234.50')
    assert.strictEqual(await cellText('E4'), '4.5')
