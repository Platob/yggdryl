PY_FILE_CHAIN = re.compile(
    r"(?P<head>(?:pathlib\.)?Path\(__file__\)(?:\.resolve\(\))?)"
    r"(?P<tail>(?:\.parent(?![\w\[]))+|\.parents\[(?P<n>\d+)\])"
)
JS_DIRNAME_JOIN = re.compile(
    r"(?P<head>\bjoin\(\s*__dirname)(?P<segs>(?:\s*,\s*'[^'\n]*')+)(?P<close>\s*\))"
)
JS_RELATIVE_REQUIRE = re.compile(r"(?P<head>\brequire\(\s*)(?P<q>['\"])(?P<spec>\.{1,2}/[^'\"\n]*)(?P=q)")


class Moves:
    """Every move this script makes, file by file, for paths spelled elsewhere."""

    def __init__(self) -> None:
        self.files: dict[str, str] = {}

    def add(self, old: str, new: str) -> None:
        self.files[old] = new

    def new_of(self, old: str) -> str:
        if old in self.files:
            return self.files[old]
        for src, dst in self.files.items():
            if old.startswith(src + "/"):
                return dst + old[len(src):]
        return old


def reanchor_python(text: str, old: str, new: str, moves: Moves, where: str) -> str:
    old_path = pathlib.PurePosixPath(old)
    new_path = pathlib.PurePosixPath(new)

    def swap(match: re.Match[str]) -> str:
        if match.group("n") is not None:
            depth = int(match.group("n"))
        else:
            depth = match.group("tail").count(".parent") - 1
        parents = list(old_path.parents)
        if depth >= len(parents):
            residue(where, f"`{match.group(0)}` climbs above the repository")
            return match.group(0)
        target = moves.new_of(parents[depth].as_posix())
        new_parents = [p.as_posix() for p in new_path.parents]
        if target not in new_parents:
            residue(where, f"`{match.group(0)}` reached `{parents[depth]}`, which `{new}` has no parent at")
            return match.group(0)
        j = new_parents.index(target)
        tail = f".parents[{j}]" if match.group("n") is not None else ".parent" * (j + 1)
        return match.group("head") + tail

    return PY_FILE_CHAIN.sub(swap, text)


def reanchor_javascript(text: str, old: str, new: str, moves: Moves, where: str) -> str:
    old_dir = posix_dirname(old)
    new_dir = posix_dirname(new)

    def resolve(segments: list[str]) -> str:
        return os.path.normpath(os.path.join(old_dir, *segments)).replace(os.sep, "/")

    def rel(target: str) -> list[str]:
        return os.path.relpath(target, new_dir).replace(os.sep, "/").split("/")

    def swap_join(match: re.Match[str]) -> str:
        segments = re.findall(r"'([^'\n]*)'", match.group("segs"))
        target = moves.new_of(resolve(segments))
        parts = rel(target)
        if parts == segments:
            return match.group(0)
        return match.group("head") + "".join(f", '{p}'" for p in parts) + match.group("close")

    def swap_require(match: re.Match[str]) -> str:
        spec = match.group("spec")
        target = moves.new_of(resolve(spec.split("/")))
        parts = "/".join(rel(target))
        if not parts.startswith("."):
            parts = "./" + parts
        if parts == spec:
            return match.group(0)
        return f"{match.group('head')}{match.group('q')}{parts}{match.group('q')}"

    text = JS_DIRNAME_JOIN.sub(swap_join, text)
    return JS_RELATIVE_REQUIRE.sub(swap_require, text)


