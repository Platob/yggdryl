    market_names = names.names | PY_MOVED_MODULES
    text, dropped = drop_imports(text, f"{PY_CORE}/__init__.py", PY_MOVED_MODULES, market_names)
    text = drop_all_entries(text, market_names, f"{PY_CORE}/__init__.py")
