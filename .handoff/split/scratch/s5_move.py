class JsRewriter:
    def __init__(self, runtime: set[str], types: set[str]) -> None:
        self.runtime = runtime
        self.types = types | runtime

    def rewrite(self, code: str, where: str, roots: tuple[str, ...] = (), market_root: bool = False) -> str:
        """`roots` spell this package's own root (`'..'` from `tests/`): the market's when `market_root`."""
        original = code
        code = re.sub(r"(['\"])yggdryl/book\1", r"\1yggdryl-market/book\1", code)
        code = self.destructured(code)
        code = self.imports(code, roots, market_root)
        code = self.namespaced(code, where)
        code = self.child_scripts(code, where, market_root)
        if market_root:
            # A pin that a hidden native stays off the surface reads this package's.
            code = re.sub(r"\bin require\((['\"])yggdryl\1\)", r"in require(\1yggdryl-market\1)", code)
        return code if code != original else original

    def child_scripts(self, code: str, where: str, market_root: bool) -> str:
        """A script a test runs in a child process, its package handed in as `process.argv`."""
        scripts = re.findall(r"(?:const|let|var)\s*\{([^{}]*)\}\s*=\s*require\(process\.argv\[\d+\]\)", code)
        if not scripts or re.search(r"require\.resolve\((['\"])yggdryl-market\1\)", code):
            # None, or a file that already hands its children both packages.
            return code
        kinds = set()
        for body in scripts:
            keys = [item.split(":")[0].strip() for item in js_items(body)]
            market = [key for key in keys if key in self.runtime]
            kinds.add("market" if market and len(market) == len(keys) else "mixed" if market else "core")
        if kinds == {"market"}:
            return re.sub(r"require\.resolve\((['\"])yggdryl\1\)", r"require.resolve(\1yggdryl-market\1)", code)
        if "mixed" in kinds or ("market" in kinds and "core" in kinds):
            residue(where, "a child-process script takes the package from `process.argv` and names both packages; hand it both")
        return code

    def bucket(self, key: str, uses_market_only: dict[str, bool]) -> str:
        if key in self.runtime:
            return "market"
        if key in ("enums", "fields") and key in uses_market_only:
            return "market" if uses_market_only[key] else "both"
        return "core"

    def member_uses(self, code: str, local: str, keys: list[str]) -> tuple[list[str], list[str]]:
        inside = js_literal_map(code)
        market, other = [], []
        for found in re.finditer(rf"(?<![\w$])(?:(?<=\.\.\.)|(?<!\.)){re.escape(local)}\.([A-Za-z_$][\w$]*)", code):
            if inside[found.start()]:
                continue
            (market if found.group(1) in keys else other).append(found.group(1))
        return market, other

    def destructured(self, code: str) -> str:
        while True:
            inside = js_literal_map(code)
            changed = False
            for match in JS_DESTRUCT.finditer(code):
                if inside[match.start("kw")]:
                    continue
                items = js_items(match.group("body"))
                core_items, market_items = [], []
                renames: list[tuple[str, str, str]] = []
                for item in items:
                    key, _, local = item.partition(":")
                    key, local = key.strip(), (local.strip() or key.strip())
                    if key in self.runtime:
                        market_items.append(item)
                        continue
                    where = self.split_item(code, key, local) if key in ("enums", "fields") else "core"
                    if where == "alias":
                        alias = "marketEnums" if key == "enums" else "marketFields"
                        core_items.append(item)
                        market_items.append(f"{key}: {alias}")
                        renames.append((local, alias, "|".join(JS_ENUMS if key == "enums" else JS_FIELDS)))
                    else:
                        (market_items if where == "market" else core_items).append(item)
                if not market_items:
                    continue
                multiline = "\n" in match.group("body")
                kw = match.group("kw")
                indent = match.group("indent")
                quote = match.group("q")
                parts = []
                if core_items:
                    parts.append(js_render(f"{kw} ", core_items, f" = require({quote}yggdryl{quote})", indent, multiline))
                parts.append(js_render(f"{kw} ", market_items, f" = require({quote}yggdryl-market{quote})", indent, multiline))
                code = code[: match.start()] + "\n".join(parts) + code[match.end():]
                for local, alias, keys in renames:
                    code = self.rename_members(code, local, alias, keys)
                changed = True
                break
            if not changed:
                return code

    def rename_members(self, code: str, local: str, alias: str, keys: str) -> str:
        inside = js_literal_map(code)
        out = []
        last = 0
        for found in re.finditer(rf"(?<![\w$])(?:(?<=\.\.\.)|(?<!\.)){re.escape(local)}(?=\.(?:{keys})\b)", code):
            if inside[found.start()]:
                continue
            out.append(code[last:found.start()])
            out.append(alias)
            last = found.end()
        out.append(code[last:])
        return "".join(out)

    def split_item(self, code: str, key: str, local: str) -> str:
        """`market`, `core`, or `alias` for a namespace both packages answer."""
        keys = JS_ENUMS if key == "enums" else JS_FIELDS if key == "fields" else None
        if keys is None:
            return "market" if key in self.types else "core"
        market, other = self.member_uses(code, local, keys)
        if not market:
            return "core"
        return "market" if not other else "alias"

    def imports(self, code: str, roots: tuple[str, ...], market_root: bool = False) -> str:
        while True:
            inside = js_literal_map(code)
            changed = False
            for match in TS_IMPORT.finditer(code):
                if inside[match.start()] or match.group("spec") not in ("yggdryl", *roots):
                    continue
                spec = match.group("spec")
                items = js_items(match.group("body"))
                market, core = [], []
                renames = []
                for item in items:
                    bare = re.sub(r"^type\s+", "", item)
                    key, _, local = bare.partition(" as ")
                    key, local = key.strip(), (local.strip() or key.strip())
                    where = self.split_item(code, key, local)
                    if where == "alias":
                        alias = "marketEnums" if key == "enums" else "marketFields"
                        core.append(item)
                        market.append(f"{key} as {alias}")
                        renames.append((local, alias, "|".join(JS_ENUMS if key == "enums" else JS_FIELDS)))
                    else:
                        (market if where == "market" else core).append(item)
                at_market = spec != "yggdryl" and market_root
                if not at_market and not market:
                    continue
                if at_market and not core:
                    continue
                multiline = "\n" in match.group("body")
                kind = match.group("type") or ""
                quote = match.group("q")
                indent = match.group("indent")
                parts = []
                core_spec = "yggdryl" if at_market else spec
                market_spec = spec if at_market else "yggdryl-market"
                if core:
                    parts.append(js_render(f"import {kind}", core, f" from {quote}{core_spec}{quote}", indent, multiline))
                if market:
                    parts.append(js_render(f"import {kind}", market, f" from {quote}{market_spec}{quote}", indent, multiline))
                code = code[: match.start()] + "\n".join(parts) + code[match.end():]
                for local, alias, keys in renames:
                    code = self.rename_members(code, local, alias, keys)
                changed = True
                break
            if not changed:
                return code

    def split_alias_destructuring(self, code: str, local: str, alias: str) -> tuple[str, bool]:
        """`const { a, b } = yggdryl`: the market's names destructured from the market's alias."""
        pattern = re.compile(rf"(?m)^(?P<indent>[ \t]*)(?P<kw>const|let|var)\s*\{{(?P<body>[^{{}}]*)\}}\s*=\s*{re.escape(local)}\b")
        changed = False
        while True:
            inside = js_literal_map(code)
            for match in pattern.finditer(code):
                if inside[match.start("kw")]:
                    continue
                items = js_items(match.group("body"))
                core_items, market_items, renames = [], [], []
                for item in items:
                    key, _, name = item.partition(":")
                    key, name = key.strip(), (name.strip() or key.strip())
                    if key in self.runtime:
                        market_items.append(item)
                        continue
                    where = self.split_item(code, key, name) if key in ("enums", "fields") else "core"
                    if where == "alias":
                        renamed = "marketEnums" if key == "enums" else "marketFields"
                        core_items.append(item)
                        market_items.append(f"{key}: {renamed}")
                        renames.append((name, renamed, "|".join(JS_ENUMS if key == "enums" else JS_FIELDS)))
                    else:
                        (market_items if where == "market" else core_items).append(item)
                if not market_items:
                    continue
                multiline = "\n" in match.group("body")
                parts = []
                if core_items:
                    parts.append(js_render(f"{match.group('kw')} ", core_items, f" = {local}", match.group("indent"), multiline))
                parts.append(js_render(f"{match.group('kw')} ", market_items, f" = {alias}", match.group("indent"), multiline))
                code = code[: match.start()] + "\n".join(parts) + code[match.end():]
                for name, renamed, keys in renames:
                    code = self.rename_members(code, name, renamed, keys)
                changed = True
                break
            else:
                return code, changed

    def namespaced(self, code: str, where: str) -> str:
        """`const yggdryl = require('yggdryl')`: what it reaches of the market, from the market's."""
        keys = "|".join(sorted(self.runtime))
        uses_of = rf"\.(?=(?:{keys})\b|enums\.(?:{'|'.join(JS_ENUMS)})\b|fields\.(?:{'|'.join(JS_FIELDS)})\b)"
        inside = js_literal_map(code)
        for match in list(JS_NAMESPACE.finditer(code)):
            if inside[match.start()]:
                continue
            local = match.group("name")
            q = match.group("q")
            existing = re.search(rf"(?m)^[ \t]*(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*require\(\s*{q}yggdryl-market{q}\s*\)", code)
            alias = existing.group(1) if existing else (
                "market" if not re.search(r"(?<![\w$])(?:(?<=\.\.\.)|(?<!\.))market\b", code) else "yggdrylMarket"
            )
            code, split = self.split_alias_destructuring(code, local, alias)
            inside = js_literal_map(code)
            uses = [
                found for found in re.finditer(rf"(?<![\w$])(?:(?<=\.\.\.)|(?<!\.)){re.escape(local)}(?={uses_of})", code)
                if not inside[found.start()]
            ]
            if not uses and not split:
                continue
            out = []
            last = 0
            for found in uses:
                out.append(code[last:found.start()])
                out.append(alias)
                last = found.end()
            out.append(code[last:])
            code = "".join(out)
            if not existing:
                at = code.find(match.group(0))
                line_end = code.find("\n", at)
                line_end = len(code) if line_end == -1 else line_end
                code = code[:line_end] + f"\n{match.group('indent')}const {alias} = require({q}yggdryl-market{q})" + code[line_end:]
            inside = js_literal_map(code)
        return code


