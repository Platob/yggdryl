def ts_code(line: str) -> str:
    """A line without its `//` comment and string contents, for depth counting."""
    out = []
    quote = None
    i = 0
    while i < len(line):
        c = line[i]
        if quote:
            if c == "\\":
                i += 2
                continue
            if c == quote:
                quote = None
            i += 1
            continue
        if c in "'\"`":
            quote = c
        elif line.startswith("//", i):
            break
        else:
            out.append(c)
        i += 1
    return "".join(out)


def depth_delta(line: str) -> int:
    code = ts_code(line)
    return sum(code.count(c) for c in "{([") - sum(code.count(c) for c in "})]")


def ts_decl_end(lines: list[str], start: int) -> int:
    depth = 0
    j = start
    in_doc = False
    while j < len(lines):
        line = lines[j]
        stripped = line.strip()
        if stripped.startswith("/*") and not stripped.endswith("*/"):
            in_doc = True
        if in_doc:
            if stripped.endswith("*/"):
                in_doc = False
            j += 1
            continue
        depth += depth_delta(line)
        code = ts_code(line).rstrip()
        follows = j + 1 < len(lines) and TS_CONT_START.match(lines[j + 1]) is not None
        if depth <= 0 and not TS_CONT_END.search(code) and not follows:
            return j + 1
        j += 1
    return j


def ts_doc_start(lines: list[str], index: int) -> int:
    k = index
    if k > 0 and lines[k - 1].strip().endswith("*/"):
        k -= 1
        while k > 0 and not lines[k].strip().startswith("/**"):
            k -= 1
    return k


class Dts:
    def __init__(self, text: str) -> None:
        self.lines = text.split("\n")
        self.gone: set[int] = set()

    def text(self) -> str:
        return "\n".join(line for i, line in enumerate(self.lines) if i not in self.gone)

    def take(self, start: int, end: int) -> str:
        chunk = "\n".join(self.lines[start:end])
        self.gone.update(range(start, end))
        return chunk

    def top(self, name: str) -> list[str]:
        pattern = re.compile(
            rf"^export (?:declare )?(?:const|function|class|interface|type|enum|namespace) {re.escape(name)}\b"
        )
        chunks = []
        for i, line in enumerate(self.lines):
            if i in self.gone or not pattern.match(line):
                continue
            chunks.append(self.take(ts_doc_start(self.lines, i), ts_decl_end(self.lines, i)))
        return chunks

    def block(self, opener: re.Pattern[str]) -> list[tuple[int, int]]:
        spans = []
        for i, line in enumerate(self.lines):
            if i not in self.gone and opener.match(line):
                spans.append((i, ts_decl_end(self.lines, i)))
        return spans

    def members(self, span: tuple[int, int], names: set[str], indent: str = "  ") -> list[str]:
        start, end = span
        pattern = re.compile(
            rf"^{indent}(?:readonly |interface |namespace |type |function )?({'|'.join(re.escape(n) for n in sorted(names))})\b\s*[<(:?{{=]?"
        )
        chunks = []
        i = start + 1
        while i < end - 1:
            line = self.lines[i]
            found = pattern.match(line)
            if i not in self.gone and found and not line.startswith(indent + " "):
                stop = ts_decl_end(self.lines, i)
                chunks.append(self.take(ts_doc_start(self.lines, i), stop))
                i = stop
                continue
            i += 1
        return chunks

    def list_names(self, opener: re.Pattern[str], names: set[str]) -> list[list[str]]:
        """Drop `  Name,`/`  type Name,` lines of every matching list; answer them per list."""
        out = []
        for start, end in self.block(opener):
            dropped = []
            for i in range(start + 1, end - 1):
                found = re.fullmatch(r"\s+(type\s+)?([A-Za-z_$][\w$]*)(\s+as\s+[\w$]+)?,\s*", self.lines[i])
                if found and found.group(2) in names:
                    dropped.append(self.lines[i].strip().rstrip(","))
                    self.gone.add(i)
            out.append(dropped)
        return out


TS_IDENT = re.compile(r"(?<![\w$.'\"])([A-Z][\w$]*)\b")


def ts_identifiers(text: str) -> set[str]:
    found = set()
    in_doc = False
    for line in text.split("\n"):
        stripped = line.strip()
        if stripped.startswith("/*"):
            in_doc = not stripped.endswith("*/")
            continue
        if in_doc:
            if stripped.endswith("*/"):
                in_doc = False
            continue
        found.update(TS_IDENT.findall(ts_code(line)))
    return found


def ts_declared(text: str, exported_only: bool) -> set[str]:
    prefix = r"^export (?:declare )?" if exported_only else r"^(?:export )?(?:declare )?"
    names = set(re.findall(prefix + r"(?:const|function|class|interface|type|enum|namespace) ([A-Za-z_$][\w$]*)", text, re.M))
    if exported_only:
        for block in re.finditer(r"(?ms)^export (?:type )?\{(.*?)\}", text):
            for item in block.group(1).split(","):
                item = item.strip()
                if item:
                    names.add(item.split()[-1])
    return names


def split_declarations(root: pathlib.Path, classified: list[dict]) -> set[str]:
    """Move the market's declarations out of the core's `binding.d.ts`; answer what they export."""
    where = "node/binding.d.ts"
    path = root / "node/binding.d.ts"
    dts = Dts(read(path))
    natives = {item["name"] for item in classified}
    values = {item["name"] for item in classified if item["value"]}
    market = natives | set(DTS_MOVED)

    reexports = dts.list_names(re.compile(r"^export \{\s*$"), market)
    dts.list_names(re.compile(r"^import type \{\s*$"), market)
    dts.list_names(re.compile(r"^import \{\s*$"), market)
    type_exports = dts.list_names(re.compile(r"^export type \{\s*$"), market)

    chunks: list[str] = []
    for name in DTS_MOVED:
        found = dts.top(name)
        if not found:
            residue(where, f"no top-level declaration of `{name}` to move")
        chunks += found

    # FIX and the graph: one contiguous run from the message value to `graph`.
    starts = [i for i, line in enumerate(dts.lines) if line.startswith("export type FixValueInput =")]
    ends = [i for i, line in enumerate(dts.lines) if line == "export declare const graph: Graph"]
    if len(starts) == 1 and len(ends) == 1 and ends[0] > starts[0]:
        block = dts.take(ts_doc_start(dts.lines, starts[0]), ends[0] + 1)
        chunks.append(block.replace("declare module './index' {", "declare module 'yggdryl/implementer' {"))
    else:
        residue(where, "the FIX and graph declarations (FixValueInput .. graph) were not found as one run")

    fields_members: list[str] = []
    for span in dts.block(re.compile(r"^export interface FieldsNamespace \{")):
        fields_members += dts.members(span, set(JS_FIELDS))
    enum_members: list[str] = []
    for span in dts.block(re.compile(r"^export declare const enums: \{")):
        enum_members += dts.members(span, set(JS_ENUMS))
    augmented: list[str] = []
    for span in dts.block(re.compile(r"^declare module '\./index' \{")):
        augmented += dts.members(span, natives)

    core_text = dts.text()
    leftover = [n for n in sorted(set(DTS_MOVED) | {"Fix", "Graph", "FixMsgConstructor", "MarketItem"})
                if re.search(rf"\b{re.escape(n)}\b", re.sub(r"(?s)/\*.*?\*/|//[^\n]*", "", core_text))]
    for name in leftover:
        residue(where, f"the core's declarations still name `{name}` after the split")

    body = "\n\n".join(chunk.strip("\n") for chunk in chunks)
    if fields_members:
        body += (
            "\n\n/** The four market enum kinds' field factories, each the canonical native `Field`. */\n"
            "export interface MarketFieldsNamespace {\n" + "\n".join(fields_members) + "\n}\n\n"
            "export declare const fields: MarketFieldsNamespace"
        )
    if enum_members:
        body += "\n\nexport declare const enums: {\n" + "\n".join(enum_members) + "\n}"
    if augmented:
        body += "\n\ndeclare module 'yggdryl/implementer' {\n" + "\n".join(augmented) + "\n}"

    # What the moved text names that it does not declare: the market's own
    # natives from the addon's declarations, the core's public names from the
    # core, and a private core type made public for it.
    declared_here = ts_declared(body, exported_only=False)
    core_public = ts_declared(core_text, exported_only=True)
    core_private = ts_declared(core_text, exported_only=False) - core_public
    used = ts_identifiers(body) - declared_here
    from_implementer = sorted(n for n in used if n in natives)
    from_core = sorted(n for n in used if n not in natives and n in core_public)
    raised = sorted(n for n in used if n not in natives and n in core_private)
    for name in raised:
        new_core, count = re.subn(
            rf"(?m)^((?:declare )?(?:type|interface) {re.escape(name)}\b)", r"export \1", core_text, count=1
        )
        if count:
            core_text = new_core
            from_core.append(name)
            done(f"node declarations: `{name}` is now exported by the core, which the market's factories type with")
        else:
            residue(where, f"`{name}` is private to the core's declarations and could not be exported")
    write(path, core_text)

    head = [
        "// Declarations of `binding.js`, the loader `yggdryl-market` answers as its",
        "// package: the market and FIX doors over the classes the core's one addon",
        "// carries for them, read through `yggdryl/implementer` (DESIGN D11).",
        "// `binding.js` owns the behaviour; this file states its shapes and nothing else.",
        "",
    ]
    if from_implementer:
        head.append("import {\n" + "".join(f"  {n},\n" for n in from_implementer) + "} from 'yggdryl/implementer'")
    if from_core:
        head.append("import {\n" + "".join(f"  {n},\n" for n in sorted(set(from_core))) + "} from 'yggdryl'")
    flat_reexports = sorted({name for group in reexports for name in group}, key=lambda s: s.split()[-1])
    if flat_reexports:
        head.append("\nexport {\n" + "".join(f"  {n},\n" for n in flat_reexports) + "} from 'yggdryl/implementer'")
    flat_types = sorted({name for group in type_exports for name in group})
    if flat_types:
        head.append("\nexport type {\n" + "".join(f"  {n},\n" for n in flat_types) + "}")
    text = "\n".join(head) + "\n\n" + body.strip("\n") + "\n"
    write(root / NODE_ROOT / "binding.d.ts", text)
    exported = ts_declared(text, exported_only=True)
    done(f"node declarations: {len(chunks)} declaration(s), {len(fields_members)} field and {len(enum_members)} listing member(s), {len(augmented)} augmentation(s) moved; {len(exported)} market name(s) exported")
    return exported


