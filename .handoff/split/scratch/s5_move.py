def scan_residue(root: pathlib.Path, names: PyNames, files: list[str]) -> None:
    market_py = "|".join(sorted(names.names | names.modules))
    py_import = re.compile(rf"^\s*from yggdryl import .*\b({market_py})\b")
    js_require = re.compile(r"require\(\s*['\"]yggdryl['\"]\s*\)")
    reaching: dict[str, int] = {}
    for path in files:
        if path.startswith(".handoff/"):
            continue
        text = read(root / path)
        for number, line in enumerate(text.split("\n"), start=1):
            if py_import.match(line) and "yggdryl.market" not in line:
                residue(f"{path}:{number}", "still imports a market name from `yggdryl`")
            if re.search(r"(['\"])yggdryl/book\1", line):
                residue(f"{path}:{number}", "still names `yggdryl/book`")
        if path.startswith("python/tests/") or path.startswith("python/benchmarks/"):
            hits = len(re.findall(r"\byggdryl\.market\b", text))
            if hits:
                reaching[path] = hits
        if path.startswith("node/tests/") or path.startswith("node/benchmarks/"):
            hits = len(re.findall(r"['\"]yggdryl-market(?:/book)?['\"]", text))
            if hits:
                reaching[path] = hits
        if path.endswith(".md") and not path.startswith(".handoff/"):
            for number, line in enumerate(text.split("\n"), start=1):
                if re.search(r"`yggdryl\.(fix|graph)`", line) and "logger" not in line.lower():
                    residue(f"{path}:{number}", "prose names `yggdryl.fix`/`yggdryl.graph` bare: a Python module now `yggdryl.market.*`, or a logger name that stays - read it")
    for path, hits in sorted(reaching.items()):
        residue(path, f"a core test or benchmark reaches the market package ({hits} site(s)): re-fixture or move it (D14); it passes while CI installs both")


