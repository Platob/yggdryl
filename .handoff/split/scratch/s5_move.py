def lock_entry_dev(entry: dict) -> dict:
    """A core lock entry as a development-only entry of the market's lock."""
    if entry.get("dev"):
        return dict(entry)
    out: dict = {}
    placed = False
    for key, value in entry.items():
        if key in ("optional", "devOptional", "peer"):
            continue
        out[key] = value
        if key == "integrity" or (key == "resolved" and "integrity" not in entry):
            out["dev"] = True
            placed = True
    if not placed:
        out = {"dev": True, **out}
    return out


def market_lock(root: pathlib.Path) -> None:
    """`node/market/package-lock.json`, its registry entries the core lock's own.

    Every package the market resolves is one the core's lock already pins, so
    the market's lock is derived from it rather than resolved afresh: the same
    versions and integrity hashes, each marked development-only, the core the
    `file:..` link npm writes for it, and nothing fetched.
    """
    target = root / NODE_ROOT / "package-lock.json"
    core = json.loads(read(root / "node/package-lock.json"))
    package = json.loads(read(root / NODE_ROOT / "package.json"))
    packages = core["packages"]

    def resolve(frm: str, name: str) -> str | None:
        base = frm
        while True:
            key = (base + "/" if base else "") + "node_modules/" + name
            if key in packages:
                return key
            if not base:
                return None
            cut = base.rfind("node_modules/")
            base = base[:cut].rstrip("/")

    wanted = {**package.get("dependencies", {}), **package.get("devDependencies", {})}
    wanted.pop("yggdryl", None)
    closure: dict[str, dict] = {}
    queue = [("", name) for name in wanted]
    while queue:
        frm, name = queue.pop()
        key = resolve(frm, name)
        if key is None:
            residue(str(target.relative_to(root)), f"`{name}` (needed by `{frm or 'the package'}`) is not in the core's lock; run `npm install --package-lock-only --prefix node/market`")
            return
        if key in closure:
            continue
        closure[key] = lock_entry_dev(packages[key])
        for dep in {**packages[key].get("dependencies", {}), **packages[key].get("optionalDependencies", {})}:
            queue.append((key, dep))
    core_root = packages[""]
    linked: dict = {}
    for key, value in core_root.items():
        linked[key] = value
        if key == "version":
            linked["dev"] = True
    own: dict = {}
    for key in ("name", "version", "license", "dependencies", "devDependencies", "engines", "peerDependencies"):
        if key in package:
            own[key] = package[key]
    entries = {"": own, "..": linked}
    for key in sorted(closure) + ["node_modules/yggdryl"]:
        entries[key] = closure[key] if key in closure else {"resolved": "..", "link": True}
    lock = {
        "name": package["name"],
        "version": package["version"],
        "lockfileVersion": core.get("lockfileVersion", 3),
        "requires": True,
        "packages": entries,
    }
    write(target, json.dumps(lock, indent=2) + "\n")
    done(f"node market: package-lock.json derived from the core's lock ({len(closure)} registry entr{'y' if len(closure) == 1 else 'ies'}, the core linked)")


