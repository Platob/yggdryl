def reown_relative_imports(text: str, old_parts: list[str], new_parts: list[str], where: str) -> str:
    """A moved module's `from .x import` re-owned: the market's stay relative, the core's absolute."""
    try:
        tree = ast.parse(text)
    except SyntaxError as error:
        residue(where, f"does not parse ({error.msg}); relative imports not re-owned")
        return text
    lines = text.split("\n")
    edits = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.ImportFrom) or node.level == 0:
            continue
        base = old_parts[: len(old_parts) - (node.level - 1)]
        target = base + (node.module.split(".") if node.module else [])
        if node.module is None:
            residue(f"{where}:{node.lineno}", "`from . import` in a moved module; re-own by hand")
            continue
        if len(target) > 1 and target[0] == "yggdryl" and target[1] in PY_MOVED_MODULES:
            absolute = ["yggdryl", "market", *target[1:]]
            common = 0
            while common < min(len(absolute), len(new_parts)) and absolute[common] == new_parts[common]:
                common += 1
            level = len(new_parts) - common + 1
            prefix = "." * level + ".".join(absolute[common:])
        else:
            prefix = ".".join(target)
        line = lines[node.lineno - 1]
        spelled = re.compile(r"from\s+\.+[\w.]*")
        found = spelled.match(line, node.col_offset)
        if not found:
            residue(f"{where}:{node.lineno}", "relative import not spelled on one line; re-own by hand")
            continue
        edits.append((node.lineno - 1, found.start(), found.end(), f"from {prefix}"))
    for row, start, end, new in sorted(edits, reverse=True):
        lines[row] = lines[row][:start] + new + lines[row][end:]
    return "\n".join(lines)


def package_parts(path: str, root_dir: str, root_parts: list[str]) -> list[str]:
    relative = pathlib.PurePosixPath(path).relative_to(root_dir)
    parts = list(root_parts) + list(relative.parent.parts)
    if relative.name in ("__init__.py", "__init__.pyi"):
        return parts
    return parts


def reown_moved_python(root: pathlib.Path, planned: list[tuple[str, str]]) -> None:
    count = 0
