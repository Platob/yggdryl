def text_files(root: pathlib.Path) -> list[str]:
    out = []
    for path in tracked(root):
        parts = path.split("/")
        if any(part in SKIP_DIRS for part in parts[:-1]):
            continue
        if pathlib.PurePosixPath(path).suffix in TEXT_SUFFIXES and (root / path).is_file():
            out.append(path)
    # Files this run wrote are not tracked yet.
    for folder in (PY_ROOT, NODE_ROOT):
        for path in sorted((root / folder).rglob("*")):
            rel = path.relative_to(root).as_posix()
            if path.is_file() and path.suffix in TEXT_SUFFIXES and rel not in out and "node_modules" not in rel:
                out.append(rel)
    return out


