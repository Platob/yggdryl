def js_literal_map(code: str) -> list[bool]:
    """Which characters lie inside a string, a template literal or a comment."""
    inside = [False] * len(code)
    i = 0
    n = len(code)
    while i < n:
        c = code[i]
        if code.startswith("//", i):
            j = code.find("\n", i)
            j = n if j == -1 else j
            for k in range(i, j):
                inside[k] = True
            i = j
            continue
        if code.startswith("/*", i):
            j = code.find("*/", i + 2)
            j = n if j == -1 else j + 2
            for k in range(i, j):
                inside[k] = True
            i = j
            continue
        if c in "'\"`":
            j = i + 1
            while j < n and code[j] != c:
                if code[j] == "\\":
                    j += 1
                elif c != "`" and code[j] == "\n":
                    break
                j += 1
            for k in range(i + 1, min(j, n)):
                inside[k] = True
            i = j + 1
            continue
        i += 1
    return inside


