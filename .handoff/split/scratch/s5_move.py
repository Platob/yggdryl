class PyNames:
    """What `yggdryl.market` answers, read off the moved package."""

    def __init__(self, root: pathlib.Path) -> None:
        self.modules = set(PY_MOVED_MODULES)
        self.names: set[str] = set()
        pkg = root / PY_PKG
        for module in PY_MODULES:
            if module == "fix":
                continue
            source = pkg / f"{module}.py"
            if not source.exists():
                source = root / PY_CORE / f"{module}.py"
            if source.exists():
                self.names |= all_names(read(source))
        self.enums = set(PY_ENUMS)

    def is_market(self, name: str) -> bool:
        return name in self.names or name in self.modules


def all_names(text: str) -> set[str]:
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return set()
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets
        ):
            return {e.value for e in node.value.elts if isinstance(e, ast.Constant)}
    return set()


def render_from(module: str, aliases: list[tuple[str, str | None]], indent: str, multiline: bool) -> str:
    parts = [name if asname is None else f"{name} as {asname}" for name, asname in aliases]
    single = f"{indent}from {module} import {', '.join(parts)}"
    if not multiline and len(single) <= 99:
        return single
    body = "".join(f"{indent}    {part},\n" for part in parts)
    return f"{indent}from {module} import (\n{body}{indent})"


def statement_span(lines: list[str], node: ast.stmt) -> tuple[int, int]:
    return node.lineno - 1, node.end_lineno  # type: ignore[return-value]


class PyRewriter:
    """Re-spell one piece of Python code to name the market package where it moved."""

    def __init__(self, names: PyNames) -> None:
        self.names = names
        self.touched = 0

    # -- imports ---------------------------------------------------------------

    def rewrite(self, code: str, where: str) -> str:
        try:
            tree = ast.parse(code)
        except SyntaxError as error:
            if re.search(r"\byggdryl\.(?:" + "|".join(sorted(self.names.modules | self.names.names)) + r")\b|from yggdryl import", code):
                residue(where, f"python that does not parse ({error.msg}, line {error.lineno}) names yggdryl; re-spell by hand")
            return code
        lines = code.split("\n")
        edits: list[tuple[int, int, list[str]]] = []
        aliases_of_core = {"yggdryl"}
        needs_market = False
        enum_modules: dict[str, ast.ImportFrom] = {}
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    if alias.name == "yggdryl" and alias.asname:
                        aliases_of_core.add(alias.asname)
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                new = self.import_from(node, lines, enum_modules)
                if new is not None:
                    edits.append((node.lineno - 1, node.end_lineno, new))  # type: ignore[arg-type]
            elif isinstance(node, ast.Import):
                new_names = []
                changed = False
                for alias in node.names:
                    head, _, rest = alias.name.partition(".")
                    if head == "yggdryl" and rest and rest.split(".")[0] in self.names.modules:
                        new_names.append((f"yggdryl.market.{rest}", alias.asname))
                        changed = True
                    else:
                        new_names.append((alias.name, alias.asname))
                if changed:
                    indent = re.match(r"[ \t]*", lines[node.lineno - 1]).group(0)
                    text = indent + "import " + ", ".join(
                        n if a is None else f"{n} as {a}" for n, a in new_names
                    )
                    edits.append((node.lineno - 1, node.end_lineno, [text]))  # type: ignore[arg-type]
        for start, end, new in sorted(edits, reverse=True):
            lines[start:end] = new
        code = "\n".join(lines)
        if edits:
            self.touched += 1
        # Attribute chains: `yggdryl.Side`, `yd.fix`, `yggdryl.enums.MARKET_KINDS`.
        code, attributed = self.attributes(code, aliases_of_core)
        # A module-bound `enums` reaching a market listing.
        code, enum_import = self.enum_module_uses(code, enum_modules)
        code, state_uses = self.state_doors(code)
        if attributed:
            code = self.ensure_import(code, "import yggdryl.market", where)
        if state_uses:
            code = self.ensure_import(code, "import yggdryl.market.fix", where)
        if enum_import:
            code = self.ensure_import(code, enum_import, where)
        return self.embedded(code, where)

    def embedded(self, code: str, where: str) -> str:
        """A child interpreter's script held in a string literal, re-spelled the same way."""
        try:
            tree = ast.parse(code)
        except SyntaxError:
            return code
        spans = []
        for node in ast.walk(tree):
            if not (isinstance(node, ast.Constant) and isinstance(node.value, str) and "\n" in node.value):
                continue
            market = "|".join(sorted(self.names.names | self.names.modules | self.names.enums))
            if not re.search(r"^\s*(?:from yggdryl\b|import yggdryl\b)", node.value, re.M):
                continue
            if not re.search(
                rf"^\s*from yggdryl import [^\n]*\b({market})\b|^\s*(?:from|import) yggdryl\.({market})\b|\byggdryl\.({market})\b",
                node.value,
                re.M,
            ):
                continue
            segment = ast.get_source_segment(code, node)
            if segment is None:
                continue
            found = re.match(r'(?s)([rRbBuU]*)("""|\'\'\'|"|\')(.*)\2$', segment)
            if not found:
                residue(f"{where}:{node.lineno}", "a script in a string literal names yggdryl and could not be re-spelled in place")
                continue
            # The literal's own text, escapes as spelled: only imports and
            # attribute chains change, so an escape inside it never moves.
            inner = found.group(3)
            body = textwrap.dedent(inner)
            margin = next((line[: len(line) - len(line.lstrip())] for line in inner.split("\n") if line.strip()), "")
            new_body = PyRewriter(self.names).rewrite(body, f"{where}:{node.lineno}")
            if new_body == body:
                continue
            reindented = "\n".join(margin + line if line.strip() else line for line in new_body.split("\n"))
            if body.startswith("\n") and not reindented.startswith("\n"):
                reindented = "\n" + reindented
            start = len("\n".join(code.split("\n")[: node.lineno - 1])) + (1 if node.lineno > 1 else 0) + node.col_offset
            end = len("\n".join(code.split("\n")[: node.end_lineno - 1])) + (1 if node.end_lineno > 1 else 0) + node.end_col_offset
            spans.append((start, end, found.group(1) + found.group(2) + reindented + found.group(2)))
        for start, end, text in sorted(spans, reverse=True):
            code = code[:start] + text + code[end:]
        return code

    def import_from(self, node: ast.ImportFrom, lines: list[str], enum_modules) -> list[str] | None:
        module = node.module or ""
        indent = re.match(r"[ \t]*", lines[node.lineno - 1]).group(0)
        multiline = node.end_lineno != node.lineno
        aliases = [(a.name, a.asname) for a in node.names]
        head, _, rest = module.partition(".")
        if head != "yggdryl":
            return None
        if rest and rest.split(".")[0] in self.names.modules:
            return render_from(f"yggdryl.market.{rest}", aliases, indent, multiline).split("\n")
        if module == "yggdryl.enums":
            market = [(n, a) for n, a in aliases if n in self.names.enums]
            if not market:
                return None
            core = [(n, a) for n, a in aliases if n not in self.names.enums]
            out = []
            if core:
                out += render_from("yggdryl.enums", core, indent, multiline).split("\n")
            out += render_from("yggdryl.market.enums", market, indent, multiline).split("\n")
            return out
        if module != "yggdryl":
            return None
        for n, a in aliases:
            if n == "enums":
                enum_modules[a or n] = node
        market = [(n, a) for n, a in aliases if self.names.is_market(n)]
        if not market:
            return None
        core = [(n, a) for n, a in aliases if not self.names.is_market(n)]
        out = []
        if core:
            out += render_from("yggdryl", core, indent, multiline).split("\n")
        out += render_from("yggdryl.market", market, indent, multiline).split("\n")
        return out

    def attributes(self, code: str, aliases: set[str]) -> tuple[str, bool]:
        try:
            tokens = list(tokenize.generate_tokens(io.StringIO(code).readline))
        except (tokenize.TokenError, IndentationError, SyntaxError):
            return code, False
        inserts: list[tuple[int, int]] = []  # (line, col) where `market.` goes
        names = [t for t in tokens if t.type not in (tokenize.NL, tokenize.NEWLINE, tokenize.COMMENT, tokenize.INDENT, tokenize.DEDENT)]
        for i in range(len(names) - 2):
            a, dot, b = names[i], names[i + 1], names[i + 2]
            if a.type != tokenize.NAME or a.string not in aliases or dot.string != ".":
                continue
            if i > 0 and names[i - 1].string in (".", "import", "from"):
                continue
            if b.type != tokenize.NAME:
                continue
            if self.names.is_market(b.string):
                inserts.append(b.start)
            elif b.string == "enums" and i + 4 < len(names) and names[i + 3].string == "." and names[i + 4].string in self.names.enums:
                inserts.append(b.start)
        if not inserts:
            return code, False
        lines = code.split("\n")
        for (row, col) in sorted(inserts, reverse=True):
            line = lines[row - 1]
            lines[row - 1] = line[:col] + "market." + line[col:]
        return "\n".join(lines), True

    def enum_module_uses(self, code: str, enum_modules) -> tuple[str, str | None]:
        if not enum_modules:
            return code, None
        statement = None
        for local in enum_modules:
            uses = re.findall(rf"(?<![\w.]){re.escape(local)}\.([A-Za-z_]\w*)", code)
            market = [u for u in uses if u in self.names.enums]
            if not market:
                continue
            code = re.sub(
                rf"(?<![\w.]){re.escape(local)}\.({'|'.join(sorted(self.names.enums))})\b",
                r"market_enums.\1",
                code,
            )
            statement = "from yggdryl.market import enums as market_enums"
        return code, statement

    def state_doors(self, code: str) -> tuple[str, bool]:
        found = False
        for old, new in PY_STATE_DOORS.items():
            pattern = rf"\bState\.{old}\("
            if re.search(pattern, code):
                code = re.sub(pattern, f"yggdryl.market.fix.{new}(", code)
                found = True
        return code, found

    def ensure_import(self, code: str, statement: str, where: str) -> str:
        if re.search(rf"(?m)^[ \t]*{re.escape(statement)}\s*$", code):
            return code
        lines = code.split("\n")
        # After the last top-level `import yggdryl...`/`from yggdryl... import`,
        # else after the last top-level import, else at the top.
        try:
            tree = ast.parse(code)
        except SyntaxError:
            residue(where, f"could not place `{statement}`; add it by hand")
            return code
        anchor = None
        fallback = None
        for node in tree.body:
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                fallback = node
                text = ast.get_source_segment(code, node) or ""
                if "yggdryl" in text:
                    anchor = node
        target = anchor or fallback
        if target is None:
            lines.insert(0, statement)
        else:
            lines.insert(target.end_lineno, statement)  # type: ignore[arg-type]
        return "\n".join(lines)


