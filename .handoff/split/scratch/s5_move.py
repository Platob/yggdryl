def drop_imports(text: str, where: str, modules: set[str], names: set[str]) -> tuple[str, list[str]]:
    """Drop whole `from .<module>` statements and single names from the others.

    Answers the text and every whole statement dropped, as it was spelled.
    """
    tree = ast.parse(text)
    lines = text.split("\n")
    removals: list[tuple[int, int, list[str]]] = []
    dropped: list[str] = []
    for node in tree.body:
        if not isinstance(node, ast.ImportFrom):
            continue
        start, end = node.lineno - 1, node.end_lineno
        if node.level == 1 and node.module and node.module.split(".")[0] in modules:
            dropped.append("\n".join(lines[start:end]))
            removals.append((start, end, []))
            continue
        gone = [a for a in node.names if a.name in names]
        if not gone:
            continue
        kept = [a for a in node.names if a.name not in names]
        statement = lines[start:end]
        if not kept:
            dropped.append("\n".join(statement))
            removals.append((start, end, []))
        elif end - start > 1:
            out = [
                line for line in statement
                if not re.fullmatch(
                    r"\s*(" + "|".join(re.escape(a.name) for a in gone) + r")(\s+as\s+\w+)?,?\s*",
                    line,
                )
            ]
            if len(out) != len(statement) - len(gone):
                residue(f"{where}:{node.lineno}", "an import names a market item beside another on one line; split by hand")
                continue
            removals.append((start, end, out))
            dropped.append(
                ("from ." if node.level else "from ")
                + (node.module or "")
                + " import "
                + ", ".join(a.name if a.asname is None else f"{a.name} as {a.asname}" for a in gone)
            )
        else:
            indent = re.match(r"[ \t]*", lines[start]).group(0)
            module = "." * node.level + (node.module or "")
            removals.append((start, end, [render_from(module, [(a.name, a.asname) for a in kept], indent, False)]))
            dropped.append(f"from {module} import " + ", ".join(
                a.name if a.asname is None else f"{a.name} as {a.asname}" for a in gone
            ))
    for start, end, new in sorted(removals, reverse=True):
        lines[start:end] = new
    return "\n".join(lines), dropped


def drop_all_entries(text: str, names: set[str], where: str) -> str:
    tree = ast.parse(text)
    lines = text.split("\n")
    for node in tree.body:
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            if any(isinstance(t, ast.Name) and t.id == "__all__" for t in targets):
                if node.value is None:
                    return text
                start, end = node.lineno - 1, node.end_lineno
                kept = []
                for line in lines[start:end]:
                    found = re.fullmatch(r'\s*["\']([\w.]+)["\'],?\s*', line)
                    if found and found.group(1) in names:
                        continue
                    kept.append(line)
                if end - start == 1:
                    value = ast.literal_eval(node.value)
                    kept = [lines[start].split("=")[0] + "= " + repr([v for v in value if v not in names]).replace("'", '"')]
                lines[start:end] = kept
                return "\n".join(lines)
    return text


def drop_assignments(text: str, names: set[str]) -> str:
    """Top-level assignments of `names` and the `#:` comments above each."""
    tree = ast.parse(text)
    lines = text.split("\n")
    spans = []
    for node in tree.body:
        targets = node.targets if isinstance(node, ast.Assign) else [node.target] if isinstance(node, ast.AnnAssign) else []
        if any(isinstance(t, ast.Name) and t.id in names for t in targets):
            start = node.lineno - 1
            while start > 0 and lines[start - 1].lstrip().startswith("#:"):
                start -= 1
            end = node.end_lineno
            if start > 0 and not lines[start - 1].strip() and end < len(lines) and not lines[end].strip():
                end += 1
            spans.append((start, end))
    for start, end in sorted(spans, reverse=True):
        del lines[start:end]
    return "\n".join(lines)


def drop_methods(text: str, names: set[str]) -> tuple[str, int]:
    tree = ast.parse(text)
    lines = text.split("\n")
    spans = []
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef):
            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)) and item.name in names:
                    start = min([d.lineno for d in item.decorator_list] + [item.lineno]) - 1
                    end = item.end_lineno
                    if end < len(lines) and not lines[end].strip() and start > 0 and not lines[start - 1].strip():
                        end += 1
                    spans.append((start, end))
    for start, end in sorted(spans, reverse=True):
        del lines[start:end]
    return "\n".join(lines), len(spans)


