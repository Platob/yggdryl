    arguments = parser.parse_args()
    root = arguments.tree.resolve()
    lock = GitLock(not arguments.no_git_lock)

    # Step 0: a tree this already moved is left as it is.
    if (root / PY_ROOT / "pyproject.toml").exists() or (root / NODE_ROOT / "package.json").exists():
        print(f"{PY_ROOT}/pyproject.toml or {NODE_ROOT}/package.json exists: the move has run on this tree; nothing changed")
        return 0
    if git(root, "status", "--porcelain").strip():
        raise SystemExit("the tree is dirty; run this on a clean tree")
    s4_landed = (root / "rust/market/Cargo.toml").exists() and (root / "rust/fix/Cargo.toml").exists()
    if not s4_landed:
        residue("rust/market, rust/fix", "S4 has not landed on this tree: `release_packages.py crates` lists the core alone, the `[leaves]` lines it names are still commented, and the docs runner and FIX paths are S3's")

    moves = Moves()
    names_before = PyNames(root)

    # Step 1-3: Python.
    planned = python_moves(root, moves)
    enum_text = extract_assignments(read(root / PY_CORE / "enums/__init__.py"), set(PY_ENUMS))
    # Step 4: Node, classified before anything moves.
    node_planned = node_moves(root, moves)
    git_moves(root, planned + node_planned, lock)
    done(f"moves: {len(planned)} Python and {len(node_planned)} Node path(s) moved by git")
    reown_moved_python(root, planned)
    dropped = core_python(root, names_before)
    reown_core_relative(root)
    native_python(root)
    market_python(root, dropped, enum_text, names_before)
    names = PyNames(root)

    version = python_version(root)
    moved_loader = node_core(root)
    node_package_json(root)
    arrow = None
    if any("apache-arrow" in read(root / old_new[1]) for old_new in node_planned if (root / old_new[1]).is_file()):
        arrow = json.loads(read(root / "node/package.json"))["dependencies"].get("apache-arrow")
    if moved_loader is not None:
        node_market_package(root, moved_loader, version, arrow)
        market_lock(root)
    classified: list[dict] = []
    if shutil.which("node"):
        listing = subprocess.run(
            ["node", str(root / "node/scripts/market-natives.js"), "--list"],
            capture_output=True, text=True, check=False,
        )
        if listing.returncode == 0:
            classified = json.loads(listing.stdout)
        else:
            residue("node/scripts/market-natives.js", f"--list failed: {listing.stderr.strip()[:300]}")
    else:
        residue("node/scripts/market-natives.js", "node is not on PATH: run it to write implementer.js and node/market/index.*")
    exported: set[str] = set()
    if classified:
        exported = split_declarations(root, classified)
        generate = subprocess.run(["node", str(root / "node/scripts/market-natives.js")], capture_output=True, text=True, check=False)
        if generate.returncode != 0:
            residue("node/scripts/market-natives.js", f"failed: {generate.stderr.strip()[:300]}")
        else:
            done("node: implementer.js's list, node/market/index.js and index.d.ts generated")

    # Step 6b: the Node core suite re-fixtured, on its own text before references move.
    refixture_node(root, lock)
    # Step 8 first: its anchors are the tools' own text, before paths move in it.
    tooling(root)
    # Step 7: references and paths.
    files = text_files(root)
    reanchor_moved(root, moves)
    plain_paths(root, moves, files)
    python_references(root, names, files)
    js_names = set(JS_RUNTIME) | {item["name"] for item in classified} | exported
    javascript_references(root, JsRewriter(set(JS_RUNTIME), js_names - {"enums", "fields"}), files)

    # Step 8-11.
    rehome_bindings(root, names)
    ci(root)
    release(root)
    agents(root)

    with lock:
        git(root, "add", "-A", PY_ROOT, NODE_ROOT, "node/implementer.js", "node/scripts/market-natives.js", "scripts/release_packages.py")

    scan_residue(root, names, text_files(root))
    arguments.residue.parent.mkdir(parents=True, exist_ok=True)
    body = "# S5 residue\n\n" + ("\n".join(RESIDUE) if RESIDUE else "none") + "\n\n## Done\n\n" + "\n".join(f"- {d}" for d in DONE) + "\n"
    arguments.residue.write_text(body, encoding="utf-8")
    done(f"residue: {len(RESIDUE)} item(s) in {arguments.residue}")
    return 0


