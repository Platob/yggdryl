    """Cut from the line `start` begins to the line `end` begins; answer both halves."""
    if text.count(start) != 1 or text.count(end) != 1:
        residue(where, f"cut anchors matched {text.count(start)}/{text.count(end)} times: {start.strip()[:70]!r}")
        return text, None
    a = text.index(start)
    b = text.index(end)
    if b < a:
        residue(where, f"cut anchors out of order: {start.strip()[:70]!r}")
        return text, None
    return text[:a] + text[b:], text[a:b]


