def test_block(text: str, start: str, where: str) -> str | None:
    """One top-level `test(...)` block, from its opening line to its closing `})`."""
    if text.count(start) != 1:
        residue(where, f"anchor matched {text.count(start)} times: {start.strip()[:80]!r}")
        return None
    at = text.index(start)
    end = text.find("\n})\n", at)
    if end < 0:
        residue(where, f"no closing `}})` after {start.strip()[:60]!r}")
        return None
    return text[at : end + len("\n})\n")]


def indent_block(block: str) -> str:
    return "".join(("  " + line) if line.strip() else line for line in block.splitlines(keepends=True))


