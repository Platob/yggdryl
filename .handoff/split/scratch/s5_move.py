FENCE = re.compile(
    r"(?m)^(?P<indent>[ \t]*)```(?:\{ *\.(?P<braced>[a-z]+)[^}\n]*\}|(?P<lang>[a-z]+)[^\n]*)\n"
    r"(?P<code>(?:.*\n)*?)(?P=indent)```"
)


def map_fences(text: str, language: str, rewrite, where: str) -> str:
    """Rewrite every fenced block of `language`, dedented, and indent it back."""
    out = []
    last = 0
    for match in FENCE.finditer(text):
        lang = match.group("braced") or match.group("lang")
        if lang != language:
            continue
        indent = match.group("indent")
        code = match.group("code")
        lines = code.split("\n")
        if any(line and not line.startswith(indent) for line in lines):
            continue
        body = "\n".join(line[len(indent):] for line in lines)
        new = rewrite(body, f"{where}:{line_of(text, match.start())}")
        if new == body:
            continue
        new_code = "\n".join(indent + line if line else line for line in new.split("\n"))
        out.append(text[last:match.start("code")])
        out.append(new_code)
        last = match.end("code")
    out.append(text[last:])
    return "".join(out)


